def add_input_value():
    cifra1 = int(input("Spune o cifra?"))
    cifra2 = int(input("Spune o alta cifra?"))
    cifra3 = int(input("Spune o a treia cifra?"))
    print(f"Suma cifrelor este {cifra1 + cifra2 + cifra3}, diferenta lor este {cifra1 - cifra2 - cifra3}, catul lor este {cifra1 // cifra2 // cifra3}, iar produsul lor este {cifra1 * cifra2 * cifra3}")
add_input_value()
